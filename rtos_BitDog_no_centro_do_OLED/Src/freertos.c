/**
* @brief Function implementing the oledTask thread.
* @param argument: Not used
* @retval None
*
*  O comportamento desta tarefa é descrita a seguir:
*
* 1. Limpa o display (preenche com cor preta)
* 2. Atualiza o display físico
* 3. Aguarda 3 segundos (osDelay)
* 4. Renderiza manualmente um bitmap monocromático (80x60 pixels)
*    - O bitmap é armazenado em memória como um array linear de 600 bytes
*    - Cada byte representa 8 pixels horizontais (formato MONO_HLSB)
*    - A renderização é feita pixel a pixel utilizando ssd1306_DrawPixel()
*    - Um deslocamento horizontal (OFFSET) é aplicado ao índice do bitmap
* 5. Atualiza o display com a imagem desenhada
* 6. Aguarda 6 segundos
* 7. Repete o ciclo indefinidamente
*
*/
/* USER CODE END Header_OledTask */
void OledTask(void *argument)
{
	/* USER CODE BEGIN OledTask */
	/* Inicialiar o driver ssd1306 */
	ssd1306_Init();
	/* Infinite loop */
	for(;;)
	{
		ssd1306_Fill(Black);
		ssd1306_UpdateScreen();
		osDelay(3000);

		/* ===================== Desenho do Bitmap ===================== */

		/**
		 * @brief Desenha a imagem BitDog (versão grande) no framebuffer do SSD1306.
		 *
		 * A imagem possui resolução de 80×60 pixels e está armazenada em formato
		 * monocromático (1 bit por pixel), com organização horizontal e bit menos
		 * significativo primeiro (MONO_HLSB).
		 *
		 * Os dados da imagem estão contidos em um buffer linear de 600 bytes
		 * (10 bytes por linha × 60 linhas). Cada byte representa 8 pixels
		 * horizontais consecutivos.
		 *
		 * O acesso ao bitmap considera um deslocamento inicial (@ref OFFSET),
		 * permitindo compensar um offset horizontal presente na origem dos dados
		 * (por exemplo, quando a imagem foi extraída de um framebuffer maior ou
		 * com stride diferente).
		 *
		 * A posição de desenho (24, 2) foi escolhida para centralizar a imagem
		 * horizontalmente em um display de 128×64 pixels.
		 *
		 * Este código é funcionalmente equivalente à chamada em MicroPython:
		 * @code
		 * oled.blit(fbuf_bdbig, 24, 2)
		 * @endcode
		 *
		 * @note O código valida o índice do buffer para evitar acesso fora dos
		 *       limites do bitmap.
		 */
		for (uint8_t y = 0; y < 60; y++) {
			for (uint8_t x = 0; x < 10; x++) {
				/* Índice do byte no bitmap (MONO_HLSB) */
				uint32_t byte_index = OFFSET + y * 10 + x;
				if (byte_index < 600) {
					for (uint8_t bit = 0; bit < 8; bit++) {

						/* Bit correspondente ao pixel dentro do byte */
						uint8_t bit_mask = 1 << (bit & 0x07);

						/* Testa se o pixel está ativo */
						if (bitdog_big[byte_index] & bit_mask) {
							ssd1306_DrawPixel(24+(x*8+(7-bit)), 2+y, White);
						}
					}
				}
			}
		}
		ssd1306_UpdateScreen();
		osDelay(6000);
	}
	/* USER CODE END OledTask */
}

